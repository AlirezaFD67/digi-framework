"use client";

// ============================================================================
// IMPORTS
// ============================================================================

import { useEffect, useState } from "react";

import { LoadingScreen } from "./index";

// ============================================================================
// COMPONENT
// ============================================================================

export default function SplashScreen() {
  // ============================================================================
  // HOOKS & STATE
  // ============================================================================

  const [mounted, setMounted] = useState(false);

  // ============================================================================
  // EFFECTS
  // ============================================================================

  useEffect(() => {
    setMounted(true);
  }, []);

  // ============================================================================
  // RENDER
  // ============================================================================

  if (!mounted) {
    return null;
  }

  return <LoadingScreen />;
}
